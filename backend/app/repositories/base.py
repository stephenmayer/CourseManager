"""Storage interfaces.

The split mirrors who owns the data in production:
- ReferenceData is read-only here because students and the catalog are owned by the SIS.
- RequestRepository is read/write because counselors create and edit requests in this app.

Today both are backed by seed JSON in memory. Swapping in a real API client or database means
writing a new class that satisfies one of these protocols; routes, services, and rules don't change.
"""

from typing import Protocol

from app.models import Course, CourseRequest, HistoryEvent, PlanStatus, Student


class ReferenceData(Protocol):
    def list_students(self) -> list[Student]: ...
    def get_student(self, student_id: str) -> Student | None: ...
    def list_courses(self) -> list[Course]: ...
    def get_course(self, code: str) -> Course | None: ...


class RequestRepository(Protocol):
    def list_requests(self, student_id: str | None = None) -> list[CourseRequest]: ...
    def get_request(self, request_id: str) -> CourseRequest | None: ...
    def save_request(self, request: CourseRequest) -> CourseRequest: ...
    def delete_request(self, request_id: str) -> None: ...

    def get_status(self, student_id: str) -> PlanStatus: ...
    def set_status(self, student_id: str, status: PlanStatus) -> None: ...

    def list_history(self, student_id: str) -> list[HistoryEvent]: ...
    def add_history(self, student_id: str, event: HistoryEvent) -> None: ...
